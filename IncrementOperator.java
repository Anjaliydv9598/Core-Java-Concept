package com.Number.Program.Comment;

public class IncrementOperator {

	public static void main(String[] args) {
		int n = 10;
		n=n+1;			// n=10+1 =11
		n+=1;			// n=n+1 =12
		n++;			//Post-increment (increase by 1) =13
		++n;			//Pre-increment (also increase by 1) =14
		System.out.println(n);

	}

}
